#!/usr/bin/env node
/**
 * Fetch Google and Apple JWKS and emit Rust code suitable for pasting
 * into enclave/src/pinned_jwks.rs.
 *
 * Why a Node script and not a Rust binary: enclaves have no network,
 * so JWKS refresh is an out-of-band operation we run on a workstation.
 * Pure Node 18+ — no dependencies, no `npm install`.
 *
 * Usage:
 *   node tools/fetch-jwks.mjs > /tmp/jwks-snippet.rs
 *
 * Then paste the contents of /tmp/jwks-snippet.rs into
 * enclave/src/pinned_jwks.rs, replacing the two placeholder functions.
 * Rebuild the EIF and update the KMS key policy with the new PCR0.
 *
 * Schedule: Google rotates ~weekly, Apple rotates rarely. Plan for
 * ~weekly rebuilds in production. The enclave will refuse to verify
 * any JWT whose `kid` is not in the pinned set, so a stale JWKS means
 * "every OIDC sign fails until rebuild" — which is the safe failure
 * mode, but you'll get pages.
 */

const GOOGLE_JWKS_URL = "https://www.googleapis.com/oauth2/v3/certs";
const APPLE_JWKS_URL = "https://appleid.apple.com/auth/keys";
const GOOGLE_ISS = "https://accounts.google.com";
const APPLE_ISS = "https://appleid.apple.com";

async function fetchJwks(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`fetch ${url} failed: ${res.status} ${res.statusText}`);
  }
  const json = await res.json();
  if (!Array.isArray(json.keys)) {
    throw new Error(`malformed JWKS response from ${url}`);
  }
  return json.keys;
}

// Every value below is interpolated into a Rust string literal that is
// compiled INTO THE ENCLAVE. Anything outside the base64url alphabet
// (e.g. a `"` or `\`) would let a malformed or tampered JWKS response
// inject Rust code into the EIF, so refuse it outright. Real JWKS
// `kid`/`n`/`e`/`x`/`y` values are always base64url or hex.
const SAFE_FIELD = /^[A-Za-z0-9_-]{1,2048}$/;

function safe(key, field) {
  const v = key[field];
  if (typeof v !== "string" || !SAFE_FIELD.test(v)) {
    throw new Error(`refusing JWK field ${field}=${JSON.stringify(v)} (kid=${JSON.stringify(key.kid)}): not base64url`);
  }
  return v;
}

function rsToRustLiteral(key, iss) {
  // We only support RS256 RSA keys and ES256 P-256 EC keys.
  if (key.kty === "RSA" && key.alg === "RS256") {
    return `        PinnedJwk {
            kid: "${safe(key, "kid")}".to_string(),
            kty: "RSA".to_string(),
            alg: "RS256".to_string(),
            iss: "${iss}".to_string(),
            n: Some("${safe(key, "n")}".to_string()),
            e: Some("${safe(key, "e")}".to_string()),
            crv: None,
            x: None,
            y: None,
        }`;
  }
  if (key.kty === "EC" && key.alg === "ES256" && key.crv === "P-256") {
    return `        PinnedJwk {
            kid: "${safe(key, "kid")}".to_string(),
            kty: "EC".to_string(),
            alg: "ES256".to_string(),
            iss: "${iss}".to_string(),
            n: None,
            e: None,
            crv: Some("P-256".to_string()),
            x: Some("${safe(key, "x")}".to_string()),
            y: Some("${safe(key, "y")}".to_string()),
        }`;
  }
  // Skip unsupported algorithms — the enclave verify whitelist would
  // reject them at runtime anyway, so no need to clutter the EIF.
  return null;
}

function emitFunction(name, iss, keys) {
  const literals = keys
    .map((k) => rsToRustLiteral(k, iss))
    .filter((s) => s !== null);
  if (literals.length === 0) {
    return `fn ${name}() -> Vec<PinnedJwk> {\n    vec![]\n}`;
  }
  return `fn ${name}() -> Vec<PinnedJwk> {\n    vec![\n${literals.join(",\n")},\n    ]\n}`;
}

async function main() {
  const [googleKeys, appleKeys] = await Promise.all([
    fetchJwks(GOOGLE_JWKS_URL),
    fetchJwks(APPLE_JWKS_URL),
  ]);

  // An empty Google key set would compile to `vec![]` and make every
  // Google OIDC sign fail after the next rotation. Fail the rotation
  // instead so the currently-deployed EIF keeps serving.
  const googleSupported = googleKeys.filter((k) => rsToRustLiteral(k, GOOGLE_ISS) !== null);
  if (googleSupported.length === 0) {
    throw new Error("Google JWKS yielded no supported RS256 keys; refusing to emit an empty key set");
  }

  const now = new Date().toISOString();
  const out = [
    `// ============================================================================`,
    `// JWKS snapshot — generated by tools/fetch-jwks.mjs at ${now}`,
    `// Replace the bodies of google_jwks() and apple_jwks() in`,
    `// enclave/src/pinned_jwks.rs with the two functions below.`,
    `// `,
    `// Google keys: ${googleKeys.length} fetched`,
    `// Apple keys:  ${appleKeys.length} fetched`,
    `// ============================================================================`,
    "",
    emitFunction("google_jwks", GOOGLE_ISS, googleKeys),
    "",
    emitFunction("apple_jwks", APPLE_ISS, appleKeys),
  ];
  console.log(out.join("\n"));
}

main().catch((err) => {
  console.error("fetch-jwks failed:", err.message || err);
  process.exit(1);
});
